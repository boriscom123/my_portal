// Ключ подписки на уведомления.
//
// Задача — перевести публичный ключ VAPID из строки, которую отдаёт сервер, в
// байты, которые требует браузер. Зачем отдельным файлом: это единственная в
// клиенте чистая функция без обращений к странице, и только так её можно
// проверить тестом — остальной клиентский код без браузера не запускается.
// Ошибка здесь роняет подписку на телефоне и на сервере ничем не видна.
// Вызывается из public/app.js.

/**
 * Разворачивает base64url в байты.
 * Правильный результат для ключа VAPID — 65 байт, первый из них 4: признак
 * несжатой точки на кривой P-256.
 */
export function keyToBytes(base64url) {
  // В base64url вместо + и / стоят - и _, а дополнение '=' обычно срезано.
  const base64 = (base64url + '='.repeat((4 - (base64url.length % 4)) % 4))
    .replace(/-/g, '+')
    .replace(/_/g, '/');
  return Uint8Array.from(atob(base64), (char) => char.charCodeAt(0));
}
