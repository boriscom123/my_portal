-- Реакции превращаются в оценку по девятибалльной шкале.
--
-- Требование заказчика от 2026-09-02: вместо разных реакций («нравится»,
-- «огонь») — девять смайликов от худшего к лучшему, где пятый нейтральный.
-- Значение по-прежнему лежит в kind текстом, но теперь ограничено проверкой:
-- шкала — часть смысла данных, и опечатка в ней испортит среднее молча.
--
-- Прежние значения удаляются, а не переводятся: сопоставить «нравится»
-- какой-то цифре нельзя, не выдумав её за человека. Оценок на портале
-- к этому моменту три штуки, все проверочные.
DELETE FROM reactions WHERE kind NOT IN ('1','2','3','4','5','6','7','8','9');

ALTER TABLE reactions
  ADD CONSTRAINT reactions_kind_scale
  CHECK (kind IN ('1','2','3','4','5','6','7','8','9'));
