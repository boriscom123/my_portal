-- Титры ролика: реплики с временами и исходник без титров.
--
-- Ролик смотрят в ленте без звука, поэтому титры вшиваются в саму картинку —
-- отдельный файл субтитров площадки коротких видео не принимают. Вшивать можно
-- только по репликам с временами, а автор правит в них ослышки распознавания;
-- после правки титры вшиваются заново, и делать это надо с чистого файла, а не
-- поверх уже вшитых — иначе на кадре окажутся две строки.
-- Читается из src/services/shorts.js и src/jobs/burn-short-subtitles.js.

-- Реплики: [{ startedMs, endedMs, text }]. Пусто — расшифровки ещё нет.
ALTER TABLE shorts ADD COLUMN segments jsonb NOT NULL DEFAULT '[]';

-- Файл без титров. Пусто, пока титры не вшивали: тогда исходник — сам asset_id.
ALTER TABLE shorts ADD COLUMN source_asset_id bigint REFERENCES assets(id) ON DELETE SET NULL;
