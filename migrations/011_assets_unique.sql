-- Один файл буфера — одна запись в учёте.
--
-- Повторная обработка урока (например, после сбоя) заводила вторую запись о
-- том же файле: уборка пыталась удалить его дважды, а размер буфера считался
-- вдвое больше настоящего. Ограничение переводит это из «надо не забыть» в
-- «невозможно».
--
-- Дубликаты, накопленные до ограничения, схлопываем: оставляем свежую запись,
-- у неё позже истекает срок.
DELETE FROM assets a
 USING assets b
 WHERE a.lesson_id = b.lesson_id
   AND a.path = b.path
   AND a.id < b.id;

ALTER TABLE assets ADD CONSTRAINT assets_lesson_path_unique UNIQUE (lesson_id, path);
