-- Приложения площадок: ключи, которые автор вводит в кабинете.
--
-- Отдельно от таблицы подключений намеренно. Там — связь с конкретным каналом
-- (токены доступа), а здесь само приложение: оно существует до всякой связи,
-- переживает отключение канала и меняется независимо.
--
-- Секрет лежит зашифрованным тем же ключом, что и токены: он даёт право
-- выпускать доступ от имени приложения заказчика, и открытым текстом любой дамп
-- базы становится утечкой. Ключ живёт в окружении, поэтому дамп без него
-- бесполезен.
-- Читается из src/services/platform-apps.js.
CREATE TABLE platform_apps (
  name          text PRIMARY KEY,
  client_id     text NOT NULL DEFAULT '',
  client_secret text,
  -- Зрелость адаптера: сам публикует, готовит черновик, отдаёт архив. У YouTube
  -- до проверки приложения в Google возможен только semi — площадка всё равно
  -- оставит ролик приватным.
  mode          text NOT NULL DEFAULT 'semi' CHECK (mode IN ('auto', 'semi', 'manual')),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
