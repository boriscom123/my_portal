-- Текст ролика для площадок.
--
-- Площадка коротких видео ранжирует ролик по подписи: первой строке, словам в
-- описании и хэштегам. Чтобы написать их по делу, а не по памяти, ролик
-- расшифровывается, и по расшифровке модель готовит заготовку. Хранится всё на
-- самом ролике: у загруженного ролика нет урока, в котором лежала бы
-- расшифровка.
-- Читается из src/services/shorts.js и src/jobs/suggest-short-texts.js.

-- Расшифровка речи. Пусто — ещё не считали: считается по кнопке и один раз на
-- файл, замена файла её сбрасывает.
ALTER TABLE shorts ADD COLUMN transcript text;

-- Хэштеги без решётки: решётку ставит подпись, а в поле автор правит слова.
ALTER TABLE shorts ADD COLUMN hashtags text[] NOT NULL DEFAULT '{}';

-- Заготовка от модели — черновик для автора, как lessons.generated у урока.
ALTER TABLE shorts ADD COLUMN generated jsonb NOT NULL DEFAULT '{}';
