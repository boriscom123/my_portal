-- Настройки площадок, которые не про OAuth.
--
-- У YouTube приложение описывается парой «номер и секрет», а у каналов —
-- адресом самого канала, и у MAX вдобавок своим токеном бота. Заводить под
-- каждую площадку свои колонки значит получить таблицу, где половина всегда
-- пуста: набор полей у площадок разный и будет разным дальше.
--
-- Поэтому jsonb: сюда ложится то, что своё у каждой площадки. Секреты сюда НЕ
-- кладутся — для них есть client_secret, он шифруется.
-- Читается из src/services/platform-apps.js.
ALTER TABLE platform_apps ADD COLUMN settings jsonb NOT NULL DEFAULT '{}'::jsonb;
