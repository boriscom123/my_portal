-- Поиск по словам внутри уроков.
--
-- Встроенный полнотекстовый поиск postgres с русским словарём: он знает
-- морфологию, поэтому «контейнер» находит «контейнеры». Отдельный поисковый
-- движок сюда не ставим — это ещё один сервис на машине, где памяти меньше
-- четырёх гигабайт на все проекты, ради десятков уроков.
--
-- Индекс по вычисляемому полю, а не по колонке: хранить второй раз тот же
-- текст незачем, а GIN по выражению работает так же. Выражение в индексе и в
-- запросе обязано совпадать дословно, иначе индекс не применится и поиск
-- пойдёт перебором — на глаз это незаметно, пока уроков мало.
-- Читается из src/services/search.js.
CREATE INDEX transcript_segments_search_idx
  ON transcript_segments USING gin (to_tsvector('russian', text));
