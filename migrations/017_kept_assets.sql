-- Файлы витрины живут, пока на них ссылаются, а не по сроку буфера.
--
-- Раньше срок был у всех: обложке отводилось семьдесят суток, после чего
-- уборщик её удалял, а карточка урока оставалась без картинки. Считать это
-- задумкой нельзя — витрина сама себя разрушала бы через два с половиной
-- месяца после выхода первого урока.
--
-- Теперь пустой срок означает «храним, пока используется». По сроку живёт
-- рабочее: исходник, звук, нарезки, субтитры — их не показывают зрителю, и
-- держать гигабайты вечно незачем.
-- Читается из src/services/media.js и src/jobs/cleanup-media.js.
ALTER TABLE assets ALTER COLUMN expires_at DROP NOT NULL;

-- Уже загруженные обложки тоже перестают быть временными: иначе первая же
-- уборка после этой миграции унесла бы их по старому сроку.
UPDATE assets SET expires_at = NULL WHERE kind = 'cover';
