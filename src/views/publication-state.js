// Состояние публикации человеку.
//
// Задача — одно название на состояние, где бы оно ни показывалось: на экране
// урока и на странице новости. Слово «ready» не объясняет ничего, а
// «опубликован» на приватном ролике — прямая ложь; расходись эти два экрана в
// словах, автор решил бы, что это разные вещи.
// Читается из src/views/admin-review.js и src/views/news.js.
export const PUBLICATION_STATES = {
  queued: 'в очереди',
  uploading: 'заливается',
  ready: 'лежит приватным, ждёт вашего нажатия',
  published: 'опубликован',
  failed: 'не уехал'
};

/** Название состояния. Неизвестное показываем как есть: молчать хуже. */
export function publicationLabel(state) {
  return PUBLICATION_STATES[state] ?? state;
}
