// Офлайн-страница. Задача — объяснить человеку, что произошло, вместо пустого
// белого экрана или ошибки браузера. Показывается service worker'ом, когда
// сети нет, а нужной страницы нет и в кеше.
// Кладётся в кеш оболочки при установке worker'а (public/sw.js).
import { layout } from './layout.js';

export function offlinePage(config) {
  return layout({
    config,
    path: '/offline',
    title: 'Нет сети — Solo AI Journey',
    description: 'Страница недоступна без интернета.',
    body: `
<h1>Пока нет сети</h1>
<p class="лид">Приложение открылось, но страницу загрузить не удалось. Уроки живут
на площадках, поэтому без интернета их не посмотреть.</p>
<p>Когда сеть вернётся, всё заработает само — обновлять ничего не нужно.</p>
<p><a class="кнопка-знак" href="/">Попробовать снова</a></p>`
  });
}
