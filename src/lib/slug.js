// Адрес урока из его заголовка.
//
// Задача — получить из «Планирование системы для автоматизации» строку
// «planirovanie-sistemy-dlya-avtomatizacii». Зачем латиницей: адрес урока
// живёт в ссылках, которые люди пересылают и вставляют в описания на
// площадках, а кириллица там превращается в проценты — читать такую ссылку
// невозможно, и половина сервисов её ломает при переносе строки.
//
// Правило проекта «имена латиницей» здесь тоже действует: адрес — это имя.
// Вызывается из src/routes/admin.js.

// Побуквенная замена. Щ и ю дают по несколько латинских букв, поэтому это
// таблица, а не сдвиг кода.
//
// Ключи в кавычках намеренно: без них линтер видит в них имена и справедливо
// ругается на кириллицу. Это данные, а не имена, и записаны они строками.
const LETTERS = {
  'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'е': 'e', 'ё': 'e',
  'ж': 'zh', 'з': 'z', 'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm',
  'н': 'n', 'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u',
  'ф': 'f', 'х': 'h', 'ц': 'c', 'ч': 'ch', 'ш': 'sh', 'щ': 'sch', 'ъ': '',
  'ы': 'y', 'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya'
};

// Длина адреса. Восемьдесят знаков — предел, за которым ссылка перестаёт
// помещаться в строку и переносится в мессенджерах.
const MAX_LENGTH = 80;

/** Переписывает кириллицу латиницей, остальное оставляет как есть. */
export function transliterate(text) {
  return String(text)
    .toLowerCase()
    .split('')
    .map((letter) => (letter in LETTERS ? LETTERS[letter] : letter))
    .join('');
}

/**
 * Собирает адрес урока.
 * Пустая строка на выходе означает, что из заголовка адреса не вышло — там
 * были одни знаки препинания. Вызывающий подставляет свой запасной.
 */
export function slugify(title) {
  return transliterate(title)
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, MAX_LENGTH)
    .replace(/-+$/, '');
}

/**
 * Добавляет номер, пока адрес занят.
 * Два урока с одним адресом невозможны на уровне базы, и падать на этом при
 * заведении второго урока с похожим заголовком незачем.
 */
export function uniqueSlug(base, taken) {
  const used = taken instanceof Set ? taken : new Set(taken);
  if (!used.has(base)) return base;
  for (let index = 2; index < 1000; index += 1) {
    const candidate = `${base}-${index}`;
    if (!used.has(candidate)) return candidate;
  }
  // Тысяча уроков с одинаковым заголовком — это уже не про заголовки.
  return `${base}-${Date.now()}`;
}
