// Пределы. Заголовок — строка, которую видно целиком в ленте площадки;
// описание — абзац, который читают до раскрытия «ещё».
const TITLE_LIMIT = 70;
const DESCRIPTION_LIMIT = 400;
const TAGS_COUNT = 6;
const MIN_TAG_LENGTH = 4;

/** Режет по границе слова: разрыв посреди слова читается как опечатка. */
function cut(text, limit) {
  if (text.length <= limit) return text;
  const head = text.slice(0, limit);
  const space = head.lastIndexOf(' ');
  return `${space > limit / 2 ? head.slice(0, space) : head}…`;
}

/** Разбивает на предложения. Точка, восклицательный и вопросительный знак. */
export function sentences(text) {
  return String(text)
    .split(/(?<=[.!?])\s+/)
    .map((item) => item.trim())
    .filter(Boolean);
}

/**
 * Заголовок из расшифровки.
 *
 * Берётся не первое предложение, а первое содержательное: уроки начинаются с
 * «Итак, мы продолжаем» и «Здравствуйте», и такой заголовок не говорит о
 * содержании ничего. Если содержательного не нашлось, отдаём первое — пустой
 * заголовок хуже неточного.
 */
export function suggestTitle(text) {
  const all = sentences(text);
  if (!all.length) return '';

  const meaningful = all.find(
    (sentence) => sentence.length >= 25 && !/^(итак|здравствуйте|привет|доброго)/i.test(sentence)
  );
  const chosen = meaningful ?? all[0];
  // Знаки в конце заголовка на площадках выглядят обрывком строки: обрезка
  // часто приходится на запятую, и «…связи,…» читается как сбой.
  return cut(chosen, TITLE_LIMIT).replace(/[\s,;:.—-]+…$/, '…').replace(/[\s,;:.—-]+$/, '');
}

/**
 * Описание из начала расшифровки.
 * Собирается по предложениям, а не обрезкой по знакам: оборванная на середине
 * мысль в описании читается как ошибка загрузки.
 */
export function suggestDescription(text) {
  const all = sentences(text);
  const picked = [];
  let length = 0;

  for (const sentence of all) {
    if (length + sentence.length > DESCRIPTION_LIMIT && picked.length) break;
    picked.push(sentence);
    length += sentence.length + 1;
  }

  return cut(picked.join(' '), DESCRIPTION_LIMIT);
}

/**
 * Теги по частоте значимых слов.
 *
 * Считаются слова длиннее трёх букв, не входящие в список пустых. Порядок — по
 * частоте: слово, сказанное за урок двадцать раз, и есть его тема. Латиница
 * сюда попадает наравне с кириллицей — в уроках про docker и vps это как раз
 * нужные слова.
 */
export function suggestTags(text, count = TAGS_COUNT) {
  const counts = new Map();

  for (const word of String(text).toLowerCase().split(/[^\p{L}\p{N}-]+/u)) {
    const cleaned = word.replace(/^-+|-+$/g, '');
    if (cleaned.length < MIN_TAG_LENGTH || STOP_WORDS.has(cleaned)) continue;
    if (/^\d+$/.test(cleaned)) continue;
    counts.set(cleaned, (counts.get(cleaned) ?? 0) + 1);
  }

  return [...counts.entries()]
    // Слово, сказанное один раз, темой урока не является.
    .filter(([, times]) => times > 1)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, count)
    .map(([word]) => word);
}

/** Всё сразу — то, что уходит в поля формы одним нажатием. */
export function suggestFromTranscript(text) {
  return {
    title: suggestTitle(text),
    description: suggestDescription(text),
    tags: suggestTags(text)
  };
}
