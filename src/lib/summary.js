// Черновик заголовка, описания и тегов из расшифровки.
//
// Задача — избавить автора от чистого листа: он правит готовое, а не
// придумывает с нуля. Зачем без модели: облачного поставщика в проекте не
// будет, а модель на этой машине не помещается рядом с распознаванием.
//
// Поэтому здесь не сочинение, а извлечение: заголовок — первая связная фраза,
// описание — начало расшифровки, теги — самые частые значимые слова. Это
// заведомо грубее модели, и потому результат кладётся в поля формы, а не
// применяется сам: последнее слово за автором.
// Вызывается из src/routes/admin.js.

// Слова, по которым тег не делают: они частые в любой речи и ничего не
