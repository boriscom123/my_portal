// Шкала оценки урока.
//
// Задача — держать в одном месте то, что иначе разъедется по трём: значения в
// базе, смайлики на кнопках и подписи для чтения с экрана. Требование
// заказчика: девять ступеней, пятая — ровно середина, нейтральная оценка.
//
// Зачем шкала, а не набор разных реакций вроде «нравится» и «огонь»: у оценки
// есть среднее, и «7,2 из 9 по 34 голосам» автору говорит о уроке больше, чем
// девять несравнимых счётчиков.
//
// Вызывается из src/services/feedback.js (проверка) и src/views/lesson.js
// (кнопки).

/**
 * Девять ступеней от худшей к лучшей. Порядок здесь — порядок кнопок на
 * экране, менять его нельзя: человек запоминает положение, а не смайлик.
 * Подпись обязательна — кнопка из одного смайлика непонятна и не читается
 * программой чтения с экрана.
 */
export const SCALE = [
  { value: '1', emoji: '😠', label: 'зря потратил время' },
  { value: '2', emoji: '😞', label: 'плохо' },
  { value: '3', emoji: '😕', label: 'слабо' },
  { value: '4', emoji: '🙁', label: 'скорее не понравилось' },
  { value: '5', emoji: '😐', label: 'нормально' },
  { value: '6', emoji: '🙂', label: 'скорее понравилось' },
  { value: '7', emoji: '😊', label: 'хорошо' },
  { value: '8', emoji: '😃', label: 'очень хорошо' },
  { value: '9', emoji: '🤩', label: 'лучший урок' }
];

/** Нейтральная середина. Пятая из девяти — ровно посередине. */
export const MIDDLE = SCALE[Math.floor(SCALE.length / 2)].value;

const ALLOWED = new Set(SCALE.map((step) => step.value));

/** Проверка, что оценка с этой шкалы. Вызывается перед записью в базу. */
export function isRatingOnScale(value) {
  return ALLOWED.has(String(value));
}
