// Очередь обработки уроков.
//
// Задача — дать приложению и воркеру одно место, где записаны имена шагов и
// параметры подключения. Зачем очередь вообще: шаги конвейера идут минутами и
// часами, а HTTP-запрос столько не живёт; к тому же упавший шаг должен
// повторяться сам, с нарастающей паузой, а не терять урок.
// Вызывается из src/app.js (постановка задач) и src/worker.js (исполнение).
import { Queue, Worker } from 'bullmq';
import IORedis from 'ioredis';

/**
 * Имена шагов конвейера. Строками в одном месте, а не свободным текстом по
 * вызову: опечатка в имени означает задачу, которая никогда не выполнится, и
 * заметить это можно только по уроку, застрявшему на середине.
 */
export const JOBS = {
  extractAudio: 'extractAudio',
  transcribe: 'transcribe',
  subtitles: 'subtitles',
  suggestTexts: 'suggestTexts',
  makeCoverImage: 'makeCoverImage',
  trimPauses: 'trimPauses',
  // generateTexts здесь был и убран: тексты от модели отменены вместе с
  // облаком. Имя без обработчика — ловушка: задача с ним встала бы в очередь и
  // не выполнилась никогда, а урок застрял бы на середине без объяснения.
  makeClips: 'makeClips',
  makeCover: 'makeCover',
  cleanupMedia: 'cleanupMedia',
  // Скачивание исходника по ссылке с Яндекс Диска: второй путь загрузки
  // наравне с браузером.
  fetchSource: 'fetchSource'
};

/**
 * Ставит уборку буфера на расписание.
 * Раз в час: сроки жизни файлов считаются сутками, чаще незачем; реже — и
 * переполнение диска заметит не уборщик, а упавший сервер, диск на машине
 * общий с соседними проектами.
 *
 * Зачем отдельной функцией с проверяемым именем метода: в BullMQ 6 параметр
 * repeat у add() убран, и вызов с ним не падает, а молча выполняет задачу
 * один раз. Уборка тогда работает только в минуту запуска воркера и никогда
 * больше — заметить это можно лишь по переполненному диску через месяц.
 * Вызывается из src/worker.js при старте.
 */
export async function scheduleCleanup(queue, { everyMs = 60 * 60 * 1000 } = {}) {
  return queue.upsertJobScheduler(
    'cleanup-media',
    { every: everyMs },
    { name: JOBS.cleanupMedia, data: {}, opts: { removeOnComplete: 24, removeOnFail: 24 } }
  );
}

/** Одна очередь на весь конвейер: шаги идут по порядку, а не наперегонки. */
export function queueName() {
  return 'pipeline';
}

/**
 * Приставка к ключам в Redis.
 * Двоеточие BullMQ ставит сам и в имени очереди его не допускает — оно у него
 * разделитель внутренних ключей. Поэтому из настройки его убираем.
 * Redis на сервере общий, и без приставки задачи портала смешались бы с
 * ключами соседних проектов.
 */
export function queuePrefix(config) {
  return config.redis.prefix.replace(/:+$/, '');
}

/**
 * Ключ задачи. Одинаковый ключ не встаёт в очередь дважды — это защита от
 * двойного запуска одного шага: два распознавания одного файла означают
 * двойной счёт у поставщика и гонку за одну таблицу.
 */
export function jobKey(name, lessonId) {
  return `${name}:${lessonId}`;
}

/**
 * Подключение к общему Redis сервера.
 *
 * Клиент создаётся здесь и передаётся в BullMQ готовым: в ESM-окружении он не
 * умеет собрать его сам по параметрам и падает с просьбой передать экземпляр.
 * maxRetriesPerRequest: null — требование BullMQ: он сам решает, когда
 * сдаваться, и клиент не должен обрывать долгое ожидание задачи.
 */
function connection(config) {
  const client = new IORedis(config.redis.url, { maxRetriesPerRequest: null });
  // Печатаем, КУДА подключились. На этом сервере короткое имя `redis` носят
  // два разных сервера, и приложение с воркером однажды подключились к
  // разным: задачи уходили в один, исполнитель слушал другой, и обработка
  // молча не начиналась. Адрес в журнале делает это расхождение видимым.
  client.once('ready', () => {
    const { host, port } = client.options;
    console.log(`Redis: подключено к ${host}:${port}`);
  });
  return client;
}

/**
 * Настройки повторов. Шаги конвейера падают из-за чужой сети и чужих квот, а
 * не из-за нашей логики, поэтому повтор обязателен, а пауза растёт: три
 * попытки, начиная с полуминуты.
 */
const RETRY = { attempts: 3, backoff: { type: 'exponential', delay: 30_000 } };

/**
 * Шаги, которые повторять сами не будем.
 *
 * Повтор осмыслен там, где причина отказа временная: сеть моргнула, Диск
 * ответил пятисотой. Расшифровка часового урока идёт двадцать пять минут и
 * падает по причинам постоянным — нет файла, нет модели, битый звук. Три
 * попытки означали бы семьдесят пять минут двухъядерной машины на повторение
 * одного и того же отказа, и всё это время автор видел бы «обрабатывается».
 * Решение о повторе тут за человеком: в кабинете для этого есть кнопка.
 */
const NO_RETRY_JOBS = new Set([JOBS.transcribe, JOBS.makeClips, JOBS.trimPauses]);

/**
 * Настройки для конкретного шага.
 * Вызывается из addJob; отдельной функцией — чтобы правило проверялось тестом,
 * а не жило внутри вызова.
 */
/**
 * Шаги, которые ведут урок по конвейеру. Их отказ — это застрявший урок.
 *
 * Всё остальное — довески: нарисовать обложку, предложить заголовок. Отказ
 * довеска урок не ломает, и помечать им весь урок нельзя. Заказчик увидел это
 * первым: рисование упёрлось в квоту Google, и на готовом уроке навсегда
 * повисло «обработка упала» с чужим текстом про биллинг.
 */
const PIPELINE_JOBS = new Set([
  JOBS.fetchSource,
  JOBS.extractAudio,
  JOBS.transcribe,
  JOBS.subtitles,
  JOBS.trimPauses,
  JOBS.makeClips,
  JOBS.makeCover
]);

/** Ведёт ли шаг урок по конвейеру или это необязательный довесок. */
export function isPipelineJob(name) {
  return PIPELINE_JOBS.has(name);
}

export function jobOptions(name) {
  return NO_RETRY_JOBS.has(name) ? { attempts: 1 } : {};
}

/**
 * Ставит задачу в очередь с настройками её шага.
 * Зачем обёртка: шаги ставят друг друга из четырёх разных файлов, и правило
 * «тяжёлое не повторяем» должно жить в одном месте, а не повторяться в каждом
 * вызове — там его однажды забудут.
 * Вызывается из задач в src/jobs/ и из src/routes/.
 */
export function addJob(queue, name, data) {
  return queue.add(name, data, jobOptions(name));
}

export function createQueue(config) {
  return new Queue(queueName(), {
    connection: connection(config),
    prefix: queuePrefix(config),
    defaultJobOptions: RETRY
  });
}

/**
 * Создаёт исполнителя задач.
 * concurrency: 1 — не осторожность, а рамка: на двух ядрах параллельная
 * обработка двух уроков положит и портал, и соседние проекты этого сервера.
 */
export function createWorker(config, handlers) {
  return new Worker(
    queueName(),
    async (job) => {
      const handler = handlers[job.name];
      if (!handler) throw new Error(`Неизвестная задача: ${job.name}`);
      return handler(job.data, job);
    },
    { connection: connection(config), prefix: queuePrefix(config), concurrency: 1 }
  );
}
